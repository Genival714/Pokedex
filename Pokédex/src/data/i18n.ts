/** "charizard-mega-x" → "Charizard Mega X" */
export function formatName(name: string | null | undefined): string {
    if (!name) return '';
    return name
        .replace(/[-_]/g, ' ')
        .split(' ')
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join(' ');
}

export function typeLabel(type: string): string {
    return TYPE_NAMES_PT[type as TypeName] ?? formatName(type);
}

export function eggGroupLabel(name: string): string {
    return EGG_GROUPS_PT[name] ?? formatName(name);
}

export function abilityName(name: string): string {
    return ABILITY_NAMES_PT[name] ?? formatName(name);
}

/** Limpa quebras de página/linha e normaliza "POKéMON". */
export function cleanText(text: string): string {
    return text
        .replace(/[\f\n\r]/g, ' ')
        .replace(/POK[ée]MON/g, 'Pokémon')
        .replace(/\s+/g, ' ')
        .trim();
}

/** Escolhe a entrada de texto mais recente em pt-br → pt → en. */
export function pickFlavorText(entries: FlavorText[] | undefined): string | null {
    if (!entries || entries.length === 0) return null;
    const lang = (e: FlavorText) => (e.language?.name ?? '').toLowerCase();
    for (const wanted of [['pt-br', 'pt'], ['en']]) {
        const found = entries.filter((e) => wanted.includes(lang(e)));
        if (found.length) return cleanText(found[found.length - 1].flavor_text);
    }
    return null;
}

/** Tradução parcial de efeitos em inglês para português (heurística leve). */
export function translateEffect(text: string): string {
    const pairs: Array<[RegExp, string]> = [
        [/When this Pokémon/g, 'Quando este Pokémon'],
        [/This Pokémon/g, 'Este Pokémon'],
        [/the opponent/gi, 'o oponente'],
        [/in battle/g, 'em batalha'],
        [/Special Attack/g, 'Ataque Especial'],
        [/Special Defense/g, 'Defesa Especial'],
        [/\bAttack\b/g, 'Ataque'],
        [/\bDefense\b/g, 'Defesa'],
        [/\bSpeed\b/g, 'Velocidade'],
        [/\bdamage\b/g, 'dano'],
        [/\bmoves\b/g, 'movimentos'],
        [/\bweather\b/g, 'clima'],
        [/status condition/g, 'condição de status'],
        [/\bParalysis\b/g, 'Paralisia'],
        [/\bSleep\b/g, 'Sono'],
        [/\bFreeze\b/g, 'Congelamento'],
        [/\bincreases\b/g, 'aumenta'],
        [/\bdecreases\b/g, 'diminui'],
        [/\bby (\d+)%/g, 'em $1%'],
    ];
    return pairs.reduce((acc, [re, to]) => acc.replace(re, to), text.replace(/\n/g, ' '));
}
